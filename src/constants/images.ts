/** App Store–framed phone renders (1070×2242 @ screen_w=1000). */
export type AppScreenshotSources = {
  jpg: string;
  webp: string;
  avif: string;
  jpgSrcSet: string;
  webpSrcSet: string;
  avifSrcSet: string;
  width: number;
  height: number;
  sizes: string;
};

const PHONE_SIZES =
  "(max-width: 640px) 280px, (max-width: 1024px) 360px, 420px";

function shot(
  jpg: string,
  jpg860: string,
  jpg645: string,
  jpg430: string,
  webp: string,
  webp860: string,
  webp645: string,
  webp430: string,
  avif: string,
  avif860: string,
  avif645: string,
  avif430: string,
): AppScreenshotSources {
  return {
    jpg,
    webp,
    avif,
    jpgSrcSet: `${jpg430} 430w, ${jpg645} 645w, ${jpg860} 860w, ${jpg} 1070w`,
    webpSrcSet: `${webp430} 430w, ${webp645} 645w, ${webp860} 860w, ${webp} 1070w`,
    avifSrcSet: `${avif430} 430w, ${avif645} 645w, ${avif860} 860w, ${avif} 1070w`,
    width: 1070,
    height: 2242,
    sizes: PHONE_SIZES,
  };
}

