/** Responsive in-phone app screenshot sources (1290×2796 native). */
export type AppScreenshotSources = {
  jpg: string;
  webp: string;
  avif: string;
  jpgSrcSet: string;
  webpSrcSet: string;
  avifSrcSet: string;
  width: number;
  height: number;
  sizes: string;
};

const PHONE_SIZES =
  "(max-width: 640px) 280px, (max-width: 1024px) 360px, 420px";

function shot(
  jpg: string,
  jpg860: string,
  jpg645: string,
  webp: string,
  webp860: string,
  webp645: string,
  avif: string,
  avif860: string,
  avif645: string,
): AppScreenshotSources {
  return {
    jpg,
    webp,
    avif,
    jpgSrcSet: `${jpg645} 645w, ${jpg860} 860w, ${jpg} 1290w`,
    webpSrcSet: `${webp645} 645w, ${webp860} 860w, ${webp} 1290w`,
    avifSrcSet: `${avif645} 645w, ${avif860} 860w, ${avif} 1290w`,
    width: 1290,
    height: 2796,
    sizes: PHONE_SIZES,
  };
}

